void MUC_to_32(const bl_Buffer_t *buf, bl_u32_t *data)
{
	*data = (bl_u32_t)( (buf[0] << 24u) | (buf[1] << 16u) | (buf[2] << 8u) | (buf[3]) );
}



void init_crc32_table(void) {
    for (int i = 0; i < 256; ++i) {
    	bl_u32_t c = i;
        for (int j = 0; j < 8; ++j) {
            if (c & 1)
                c = 0xEDB88320 ^ (c >> 1);
            else
                c >>= 1;
        }
        crc32_table[i] = c;
    }
}


bl_u32_t CompCRC32(const bl_u8_t *data, bl_u32_t len) {
    static int table_initialized = 0;
    if (!table_initialized) {
        init_crc32_table();
        table_initialized = 1;
    }

    bl_u32_t crc = 0xFFFFFFFF;

    for (bl_u32_t i = 0; i < len; ++i) {
    	    bl_u8_t index = (crc ^ data[i]) & 0xFF;
        crc = crc32_table[index] ^ (crc >> 8);
    }

    return crc ^ 0xFFFFFFFF;
}




static bl_Return_t _APP_IsSameData(bl_Buffer_t *src, bl_Buffer_t *dest, bl_Size_t size)
{
    bl_Return_t ret = BL_ERR_OK;
    bl_Size_t i;

	for(i = 0; i < size; i++)
	{
		if(src[i] != dest[i])
		{
			ret = BL_ERR_NOT_OK;
			break;
		}
	}

    return ret;
}

bl_Return_t App_LoadBootloader(void)
{
	bl_Return_t ret = BL_ERR_NOT_OK;
	bl_Buffer_t buffer[COMM_SIZE];
	bl_Buffer_t buffer_int[COMM_SIZE] = {0x55, 0x55, 0x55, 0x55};
	bl_Buffer_t buffer_zero[COMM_SIZE] = {0x0};
	bl_Address_t address_boot = 0;
	bl_Size_t size_boot = 0;
	bl_Buffer_t buffer_readCRC[CRC_SIZE];
	bl_u32_t TempCRC32 = 0;
	bl_u32_t ReadCRC = 0;


	
	Bl_MemCpy((bl_Buffer_t *)DRIVER_STARTADDRESS, flashDrvBlk0, DRIVER_SIZE);

	do
	{
		ret = Flsif_Init();
		if(ret != BL_ERR_OK)
		{
			err_code = 0x01;
			break;
		}


		Flsif_Read((bl_Address_t)DATA_START_ADDRESS, (bl_Size_t)COMM_SIZE, buffer);
		address_boot = BL_BE32_TO_MCU((const bl_Buffer_t*)buffer);
		if(address_boot < 0x00030000 || address_boot >= 0x00050000)
		{
			ret = BL_ERR_NOT_OK;
			err_code = 0x03;
			break;
		}


		Flsif_Read((bl_Address_t)DATA_SIZE_ADDRESS, (bl_Size_t)COMM_SIZE, buffer);
		size_boot = BL_BE32_TO_MCU((const bl_Buffer_t*)buffer);
		if(size_boot == 0 || size_boot >= (bl_Size_t)BOOT_RANGE)
		{
			ret = BL_ERR_NOT_OK;
			err_code = 0x04;
			break;
		}


		/*Verify the CRC before writing to Bootloader*/
        Flsif_Read((bl_Address_t)AES_CRC_ADDRESS, (bl_Size_t)CRC_SIZE, buffer_readCRC);
        TempCRC32 = CompCRC32((const bl_u8_t *)address_boot, size_boot);
        MUC_to_32(buffer_readCRC, &ReadCRC);
        if(TempCRC32 != ReadCRC)
        {
        		err_code = 0x0F;
        		break;
        }

		Dflash_Write(BOOT_VAILD_FLAG_ADDRESS, (bl_Size_t)COMM_SIZE, buffer_zero);



		ret = Flsif_Erase((bl_Address_t)BOOT_STARTADDRESS, (bl_Size_t)BOOT_RANGE);
        if(ret != BL_ERR_OK)
        {
        		err_code = 0x05;
        		break;
        }


        ret = Flsif_Write((bl_Address_t)BOOT_STARTADDRESS, size_boot, (const bl_Buffer_t*)address_boot);
        if(ret != BL_ERR_OK)
        {
        		err_code = 0x06;
        		break;
        }


        /*Verify the CRC after writing to Bootloader*/
        Flsif_Read((bl_Address_t)AES_CRC_ADDRESS, (bl_Size_t)CRC_SIZE, buffer_readCRC);
        TempCRC32 = CompCRC32((const bl_u8_t *)BOOT_STARTADDRESS, size_boot);
        MUC_to_32(buffer_readCRC, &ReadCRC);
        if(TempCRC32 != ReadCRC)
        {
        		err_code = 0x0B;
        		break;
        }


		ret = Dflash_Write(BOOT_VAILD_FLAG_ADDRESS, (bl_Size_t)COMM_SIZE, buffer_int);
        if(ret != BL_ERR_OK)
        {
        		err_code = 0x07;
        		break;
        }


		Flsif_Read((bl_Address_t)BOOT_VAILD_FLAG_ADDRESS, (bl_Size_t)COMM_SIZE, buffer);
		ret = _APP_IsSameData(buffer, buffer_int, (bl_Size_t)COMM_SIZE);
        if(ret != BL_ERR_OK)
        {
        		err_code = 0x08;
        		break;
        }


        ret = Dflash_Write(SAPP_INVAILD_FLAG_ADDRESS, (bl_Size_t)COMM_SIZE, buffer_zero);
        if(ret != BL_ERR_OK)
        {
        		err_code = 0x09;
        }

	}while(0);

	buffer[0] = err_code; /*error start record*/
	Dflash_Write(ERROR_START_RECORD, (bl_Size_t)COMM_SIZE, buffer);

	Bl_MemSet((bl_Buffer_t *)DRIVER_STARTADDRESS, 0x00, DRIVER_SIZE);

	/*end System reset*/
	Mcu_PerformReset();

    return ret;
}

